#!/usr/bin/env node
/**
 * Write the redirects that keep the site's previous addresses working.
 *
 *   node scripts/build-redirects.mjs [--site apps/docs/dist] [--legacy out]
 *
 * Both outputs are generated from the composed site and the mapping in
 * `legacy-routes.mjs`, so a page that ships is a page both of them cover:
 *
 * - `<site>/_redirects` — the Cloudflare Pages redirect table. Every page whose
 *   path changed answers its previous path shape on the new origin with a
 *   `301`, so `/filtering/` reaches `/react/filtering/` and every showcase path
 *   under `/demo/` reaches `/react/demo/`.
 * - `<legacy>/` — a redirect-only site for the previous address
 *   (`LEGACY_SITE`), whose host cannot send a server redirect. Each page the new site
 *   serves gets a page at its previous address carrying an instant
 *   meta-refresh and a canonical link to its new URL — the form search engines
 *   read as a permanent redirect — plus a script that keeps the query string and
 *   fragment for readers. A stub on the new site is followed to its final page,
 *   so no reader takes two hops. Media, social cards, `llms*.txt`, the
 *   favicon and the search-console verification file are copied as they are:
 *   published READMEs embed the media by its previous URL, and an image cannot
 *   follow a redirect page.
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { LEGACY_SITE, legacyRoute } from "./legacy-routes.mjs";
import { DEMO_ROOT, docsRoute, FRAMEWORK, siteUrl } from "./site.mjs";
import { isRedirectPage, locsIn, SITE } from "./sitemap-routes.mjs";

const DEFAULT_SITE = fileURLToPath(
  new URL("../apps/docs/dist", import.meta.url)
);

/** Top-level entries copied to the previous address as they are. */
const COPIED = [
  "media",
  "og",
  "og.png",
  "og.svg",
  "favicon.svg",
  "llms.txt",
  "llms-full.txt",
];

/** A search-console ownership file: `google<token>.html`. */
const VERIFICATION = /^google[0-9a-f]+\.html$/;

/** An IndexNow key file: 32 hex characters, `.txt`. */
const INDEXNOW_KEY = /^[0-9a-f]{32}\.txt$/;

const REFRESH_TARGET =
  /<meta\b[^>]*http-equiv\s*=\s*["']?refresh["']?[^>]*content\s*=\s*["'][^"']*url=([^"'\s>]+)/i;

const escapeHtml = (text) =>
  text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

/**
 * Every page the composed site serves, as `{ route, file }` — a directory
 * `index.html` only, which is the form every page route takes.
 *
 * @param {string} root
 */
export const sitePages = (root) =>
  readdirSync(root, { recursive: true })
    .map((entry) => entry.split(sep).join("/"))
    .filter((rel) => rel === "index.html" || rel.endsWith("/index.html"))
    .map((rel) => ({
      route: `/${rel.slice(0, -"index.html".length)}`,
      file: join(root, rel),
    }))
    .sort((a, b) => a.route.localeCompare(b.route));

/**
 * Where a page finally leads: itself, or — for a page that only forwards —
 * the route its meta-refresh names, resolved against the page's own route.
 *
 * @param {string} route
 * @param {string} html
 * @returns {string}
 */
export const finalRoute = (route, html) => {
  if (!isRedirectPage(html)) return route;
  const target = REFRESH_TARGET.exec(html)?.[1];
  if (!target) return route;
  return new URL(target, `${SITE}${route}`).pathname;
};

/**
 * The previous path and the current route of every page the site serves:
 * `route` is where the page is built, `to` where it finally leads once the
 * site's own stubs are followed.
 *
 * @param {string} root
 * @returns {{ from: string, route: string, to: string }[]}
 */
export const addressMap = (root) =>
  sitePages(root)
    .map(({ route, file }) => ({
      from: legacyRoute(route),
      route,
      to: finalRoute(route, readFileSync(file, "utf8")),
    }))
    .sort((a, b) => a.from.localeCompare(b.from));

/**
 * The Cloudflare Pages `_redirects` table: each changed page's previous path,
 * with and without its trailing slash, plus one rule for the showcase and one
 * for the framework section's root.
 *
 * @param {string} root
 * @returns {string}
 */
export const redirectsTable = (root) => {
  const lines = [
    "# Generated by scripts/build-redirects.mjs — previous path shapes on this",
    "# origin, answered with a permanent redirect to the page's current route.",
    `/${FRAMEWORK} ${docsRoute("getting-started")} 302`,
    `/${FRAMEWORK}/ ${docsRoute("getting-started")} 302`,
  ];
  for (const { from, to } of addressMap(root)) {
    if (from === to || from.startsWith("/demo/")) continue;
    lines.push(`${from} ${to} 301`);
    if (from.length > 1) lines.push(`${from.slice(0, -1)} ${to} 301`);
  }
  lines.push(`/demo ${DEMO_ROOT} 301`, `/demo/* ${DEMO_ROOT}:splat 301`);
  return `${lines.join("\n")}\n`;
};

/**
 * One redirect page for the previous address.
 *
 * @param {string} target - The absolute URL the page has moved to.
 * @returns {string}
 */
export const redirectPage = (target) => {
  const url = escapeHtml(target);
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>AdaptTable — this page has moved</title>
    <link rel="canonical" href="${url}" />
    <meta http-equiv="refresh" content="0; url=${url}" />
    <script>location.replace(${JSON.stringify(target)} + location.search + location.hash);</script>
  </head>
  <body>
    <p>This page has moved to <a href="${url}">${url}</a>.</p>
  </body>
</html>
`;
};

/**
 * The previous address's not-found page: any path it has no page for is sent
 * to the same path on the new origin, where `_redirects` maps the previous
 * path shapes. It still answers 404, so no crawler takes it for a page.
 *
 * @returns {string}
 */
export const notFoundPage = () => {
  const base = new URL(LEGACY_SITE).pathname;
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>AdaptTable — this page has moved</title>
    <script>location.replace(${JSON.stringify(siteUrl(""))} + location.pathname.replace(${JSON.stringify(base)}, "") + location.search + location.hash);</script>
  </head>
  <body>
    <p>AdaptTable now lives at <a href="${siteUrl("/")}">${siteUrl("/")}</a>.</p>
  </body>
</html>
`;
};

/**
 * The redirect-only site for the previous address.
 *
 * @param {string} root - The composed site.
 * @param {string} out - Where to write it; replaced if it exists.
 * @returns {{ pages: number, listed: number }}
 */
export const writeLegacySite = (root, out) => {
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const moved = addressMap(root);
  for (const { from, to } of moved) {
    const file = join(out, from.slice(1), "index.html");
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, redirectPage(siteUrl(to)));
  }
  for (const entry of readdirSync(root)) {
    if (
      COPIED.includes(entry) ||
      VERIFICATION.test(entry) ||
      INDEXNOW_KEY.test(entry)
    ) {
      cpSync(join(root, entry), join(out, entry), { recursive: true });
    }
  }
  // The previous address lists the pages it forwards, so a crawler re-reads
  // each redirect rather than waiting to come across it.
  const indexed = new Set(
    locsIn(readFileSync(join(root, "sitemap.xml"), "utf8"))
  );
  const listed = moved.filter(({ route }) => indexed.has(siteUrl(route)));
  writeFileSync(
    join(out, "sitemap.xml"),
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
      `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">` +
      listed
        .map(({ from }) => `<url><loc>${LEGACY_SITE}${from}</loc></url>`)
        .join("") +
      `</urlset>\n`
  );
  writeFileSync(join(out, "404.html"), notFoundPage());
  writeFileSync(
    join(out, "robots.txt"),
    `User-agent: *\nAllow: /\n\nSitemap: ${LEGACY_SITE}/sitemap.xml\n`
  );
  return { pages: moved.length, listed: listed.length };
};

const option = (name) => {
  const at = process.argv.indexOf(`--${name}`);
  return at === -1 ? undefined : process.argv[at + 1];
};

const main = () => {
  const root = resolve(option("site") ?? DEFAULT_SITE);
  if (!existsSync(join(root, "sitemap.xml"))) {
    console.error(
      `build-redirects: no composed site at ${root} — build the docs site and ` +
        `the showcase and compose them first.`
    );
    process.exit(1);
  }
  const table = redirectsTable(root);
  writeFileSync(join(root, "_redirects"), table);
  const rules = table
    .split("\n")
    .filter((line) => /^\/\S* \S+ \d{3}$/.test(line));
  console.log(
    `build-redirects: ${rules.length} rules in ${join(root, "_redirects")}`
  );
  const legacy = option("legacy");
  if (legacy) {
    const { pages, listed } = writeLegacySite(root, resolve(legacy));
    console.log(
      `build-redirects: ${pages} redirect pages for ${LEGACY_SITE}/ ` +
        `(${listed} in its sitemap) in ${resolve(legacy)}`
    );
  }
};

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
